// @desc    Create employee
// @route   POST /api/employees
// @access  Private
export const createEmployee = asyncHandler(async (req, res) => {
  const {
    name,
    phone,
    email,
    dateOfBirth,
    gender,
    address,
    designation,
    role,
    department,
    joiningDate,
    employmentType,
    basicSalary,
    allowances,
    deductions
  } = req.body;

  // Create user account for employee
  const user = await User.create({
    name,
    email,
    password: `emp${phone.slice(-4)}`, // Temporary password
    phone,
    role: 'employee',
    module: 'all',
    createdBy: req.user._id
  });

  // Normalize phone number (ensure it's 10 digits)
  let phoneNumber = phone || '0000000000';
  if (phoneNumber.length !== 10 || !/^\d+$/.test(phoneNumber)) {
    phoneNumber = '0000000000';
  }
  
  // Ensure designation and role are valid
  const validDesignations = ['supervisor', 'engineer', 'worker', 'technician', 'manager', 'helper', 'driver', 'admin', 'other'];
  const validRoles = ['supervisor', 'engineer', 'worker', 'technician', 'helper', 'driver', 'manager', 'admin'];
  
  const finalDesignation = validDesignations.includes(designation || role) ? (designation || role) : 'other';
  const finalRole = validRoles.includes(role || designation) ? (role || designation) : 'worker';
  
  // Ensure basicSalary is a number
  const finalBasicSalary = basicSalary !== undefined && basicSalary !== null ? Number(basicSalary) : 0;
  
  // Create employee (employeeId will be auto-generated by pre-validate hook)
  const employee = await Employee.create({
    userId: user._id,
    name,
    phone: phoneNumber,
    email,
    dateOfBirth,
    gender,
    address,
    designation: finalDesignation,
    role: finalRole,
    department: department || 'other',
    joiningDate: joiningDate || new Date(),
    employmentType: employmentType || 'full_time',
    basicSalary: finalBasicSalary,
    allowances: allowances || {
      hra: 0,
      transport: 0,
      other: 0
    },
    deductions: deductions || {
      pf: 0,
      esi: 0,
      tax: 0,
      other: 0
    },
    createdBy: req.user._id
  });

  res.status(201).json({
    success: true,
    data: employee,
    message: `Employee created. Temporary password: emp${phone.slice(-4)}`
  });
});

