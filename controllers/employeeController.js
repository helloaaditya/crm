// @desc    Apply for leave
// @route   POST /api/employees/:id/leave
// @access  Private
export const applyLeave = asyncHandler(async (req, res) => {
  const employee = await Employee.findById(req.params.id);

  if (!employee) {
    return res.status(404).json({ message: 'Employee not found' });
  }

  const { leaveType, startDate, endDate, reason } = req.body;
  
  // Calculate number of days
  const start = new Date(startDate);
  const end = new Date(endDate);
  const numberOfDays = Math.ceil((end - start) / (1000 * 60 * 60 * 24)) + 1;
  
  // If comp off, check balance
  if (leaveType === 'compoff') {
    const compOffBalance = employee.compOffBalance || 0;
    if (numberOfDays > compOffBalance) {
      return res.status(400).json({ 
        message: `Insufficient comp off balance. Available: ${compOffBalance} day(s), Requested: ${numberOfDays} day(s)` 
      });
    }
  }

  employee.leaves.push({
    leaveType,
    startDate,
    endDate,
    numberOfDays,
    reason,
    status: 'pending'
  });

  await employee.save();

  res.json({
    success: true,
    data: employee,
    message: 'Leave application submitted successfully'
  });
});

// @desc    Grant comp off to employee
// @route   POST /api/employees/:id/compoff/grant
// @access  Private (Admin)
export const grantCompOff = asyncHandler(async (req, res) => {
  const employee = await Employee.findById(req.params.id);
  
  if (!employee) {
    return res.status(404).json({ message: 'Employee not found' });
  }
  
  const { days, reason, expiryDays } = req.body;
  
  if (!days || days <= 0) {
    return res.status(400).json({ message: 'Invalid number of days' });
  }
  
  // Calculate expiry date (default 90 days)
  const expiryDate = new Date();
  expiryDate.setDate(expiryDate.getDate() + (expiryDays || 90));
  
  // Add to comp off balance
  employee.compOffBalance = (employee.compOffBalance || 0) + days;
  
  // Add to history
  employee.compOffHistory.push({
    type: 'earned',
    days,
    date: new Date(),
    reason: reason || 'Comp off granted for working on holiday/overtime',
    grantedBy: req.user._id,
    expiryDate
  });
  
  await employee.save();
  
  // Notify employee
  if (employee.userId) {
    await createNotification({
      recipient: employee.userId,
      type: 'info',
      title: 'Comp Off Granted',
      message: `You have been granted ${days} day(s) of comp off. Balance: ${employee.compOffBalance} day(s)`,
      triggeredBy: req.user._id
    });
  }
  
  res.json({
    success: true,
    message: `${days} comp off day(s) granted successfully`,
    data: {
      newBalance: employee.compOffBalance,
      expiryDate
    }
  });
});

// @desc    Approve/Reject leave
// @route   PUT /api/employees/leave/:leaveId
// @access  Private
export const updateLeaveStatus = asyncHandler(async (req, res) => {
  const { status, reason } = req.body;

  const employee = await Employee.findOne({ 'leaves._id': req.params.leaveId });

  if (!employee) {
    return res.status(404).json({ message: 'Leave application not found' });
  }

  const leave = employee.leaves.id(req.params.leaveId);
  const previousStatus = leave.status;
  leave.status = status;
  leave.approvedBy = req.user._id;
  
  // If approving comp off leave, deduct from balance
  if (status === 'approved' && leave.leaveType === 'compoff' && previousStatus !== 'approved') {
    const compOffBalance = employee.compOffBalance || 0;
    employee.compOffBalance = Math.max(0, compOffBalance - (leave.numberOfDays || 0));
    
    // Add to comp off history
    employee.compOffHistory.push({
      type: 'used',
      days: leave.numberOfDays || 0,
      date: new Date(),
      reason: `Comp off used for leave from ${new Date(leave.startDate).toLocaleDateString()} to ${new Date(leave.endDate).toLocaleDateString()}`
    });
    
    console.log(`Deducted ${leave.numberOfDays} comp off days. New balance: ${employee.compOffBalance}`);
  }
  
  // If rejecting previously approved comp off, restore balance
  if (status === 'rejected' && leave.leaveType === 'compoff' && previousStatus === 'approved') {
    employee.compOffBalance = (employee.compOffBalance || 0) + (leave.numberOfDays || 0);
    console.log(`Restored ${leave.numberOfDays} comp off days. New balance: ${employee.compOffBalance}`);
  }

  await employee.save();

  // Notify employee about leave status
  if (employee.userId) {
    if (status === 'approved') {
      await createNotification({
        recipient: employee.userId,
        ...NotificationTemplates.leaveApproved(
          employee.name,
          new Date(leave.startDate).toLocaleDateString('en-IN'),
          new Date(leave.endDate).toLocaleDateString('en-IN'),
          req.user._id
        )
      });
    } else if (status === 'rejected') {
      await createNotification({
        recipient: employee.userId,
        ...NotificationTemplates.leaveRejected(reason, req.user._id)
      });
    }
  }

  res.json({
    success: true,
    data: employee,
    message: `Leave ${status} successfully`
  });
});

// @desc    Process salary
// @route   POST /api/employees/:id/salary
// @access  Private
export const processSalary = asyncHandler(async (req, res) => {
  const employee = await Employee.findById(req.params.id);

  if (!employee) {
    return res.status(404).json({ message: 'Employee not found' });
  }

  const { month, paymentMode, notes } = req.body;

  // Check if salary already processed for the month
  const existingSalary = employee.salaryHistory.find(s => s.month === month);
  if (existingSalary) {
    return res.status(400).json({ message: 'Salary already processed for this month' });
  }

  const totalAllowances = Object.values(employee.allowances).reduce((sum, val) => sum + (val || 0), 0);
  const fixedDeductions = Object.values(employee.deductions).reduce((sum, val) => sum + (val || 0), 0);
  const grossSalary = employee.basicSalary + totalAllowances;

  // Calculate leave/attendance deductions for the target month
  const [y, m] = month.split('-').map(Number);
  const monthStart = new Date(y, (m - 1), 1);
  const monthEnd = new Date(y, (m - 1) + 1, 0, 23, 59, 59, 999);
  const attendanceThisMonth = (employee.attendance || []).filter(a => {
    const d = new Date(a.date);
    return d >= monthStart && d <= monthEnd;
  });

  // Approved leaves overlapping month
  let sickApprovedDays = 0;
  let otherApprovedLeaveDays = 0;
  (employee.leaves || []).forEach(l => {
    if (l.status === 'approved') {
      const s = new Date(l.startDate);
      const e = new Date(l.endDate);
      const from = s < monthStart ? monthStart : s;
      const to = e > monthEnd ? monthEnd : e;
      if (from <= to) {
        const days = Math.ceil((to - from) / (1000*60*60*24)) + 1;
        if (l.leaveType === 'sick') sickApprovedDays += days; else otherApprovedLeaveDays += days;
      }
    }
  });
  const halfDays = attendanceThisMonth.filter(a => a.status === 'half_day').length;
  const absents = attendanceThisMonth.filter(a => a.status === 'absent').length;
  // Daily rate approximation of 26 working days
  const dailyRate = (employee.basicSalary + totalAllowances - fixedDeductions) / 26;
  const unpaidSickDays = Math.max(0, sickApprovedDays - 1);
  const leaveDeductions = Math.max(0, Math.round(((unpaidSickDays + otherApprovedLeaveDays + absents) * dailyRate + halfDays * (dailyRate/2)) * 100) / 100);

  // Hold (Retention) 5% by default
  const holdPercent = employee.holdPercent || 5;
  const prelimNet = grossSalary - fixedDeductions - leaveDeductions;
  const holdAmount = Math.max(0, Math.round((prelimNet * holdPercent / 100) * 100) / 100);
  const payableNet = Math.max(0, Math.round((prelimNet - holdAmount) * 100) / 100);

  employee.salaryHistory.push({
    month,
    basicSalary: employee.basicSalary,
    totalAllowances,
    totalDeductions: fixedDeductions + leaveDeductions + holdAmount,
    netSalary: payableNet,
    paidDate: new Date(),
    paymentMode,
    status: 'paid',
    notes
  });

  // Update hold balance accumulator
  employee.holdBalance = (employee.holdBalance || 0) + holdAmount;

  await employee.save();

  // Notify employee about salary processed
  if (employee.userId) {
    await createNotification({
      recipient: employee.userId,
      ...NotificationTemplates.salaryProcessed(month, payableNet.toFixed(2)),
      triggeredBy: req.user._id
    });
  }

  res.json({
    success: true,
    data: employee,
    message: 'Salary processed successfully',
    salaryDetails: {
      month,
      grossSalary,
      fixedDeductions,
      leaveDeductions,
      holdPercent,
      holdAmount,
      payableNet
    }
  });
});

